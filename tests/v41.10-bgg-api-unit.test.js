#!/usr/bin/env node
const fs=require('fs');const path=require('path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let n=0,ok=0;const chk=(c,m)=>{n++;if(c){ok++;console.log('OK',m)}else{console.error('FAIL',m);process.exitCode=1}};
const strip=s=>s.replace(/\/\*[\s\S]*?\*\//g,'').replace(/(^|[^:])\/\/.*$/gm,'$1');
const meta=read('supabase/functions/bgg-meta/index.ts');
const metaCode=strip(meta);
const coll=read('supabase/functions/bgg-collection/index.ts');
const shared=read('supabase/functions/_shared/bgg.ts');
const imp=read('import-bgg.js');
const brand=read('brand.js');
const giochi=read('giochi.js');
const des=read('desideri.js');
const cons=read('consigliere.js');
chk(!/api\.geekdo\.com/.test(metaCode),'bgg-meta codice senza api.geekdo.com');
chk(!/search\/boardgame/.test(metaCode),'bgg-meta codice senza scraping search/boardgame');
chk(!/wikidata\.org/.test(metaCode),'bgg-meta codice senza Wikidata');
chk(/Rimosso: api\.geekdo\.com/.test(meta),'commento audit rimozione canali');
chk(/xmlapi2\/search/.test(meta)&&/xmlapi2\/thing/.test(meta),'bgg-meta usa search+thing XML API2');
chk(/BGG_TOKEN/.test(meta)&&/Authorization: `Bearer/.test(shared),'Bearer da BGG_TOKEN server-side');
chk(/https:\/\/boardgamegeek\.com/.test(shared)&&!/https:\/\/www\.boardgamegeek\.com/.test(shared),'host senza www nello shared');
chk(/bgg_api_cache/.test(meta)&&/bgg_api_cache/.test(coll),'cache server usata');
chk(/is_admin/.test(coll)&&!/is_staff\(/.test(coll),'collection solo is_admin');
chk(/excludesubtype=boardgameexpansion/.test(coll)&&/subtype=boardgameexpansion/.test(coll),'base+espansioni separate');
chk(/accept202|status === 202/.test(shared),'gestione 202');
chk(/429/.test(shared),'gestione 429');
chk(!/BGG_TOKEN/.test(imp),'client import senza BGG_TOKEN');
chk(/userStep/.test(imp)&&/bgg-collection/.test(imp),'UI username attiva');
chk(!/aria-disabled','true'/.test(imp),'riga username non disabilitata');
chk(/powered-by-bgg\.png/.test(imp)&&/href='https:\/\/boardgamegeek\.com'/.test(imp),'logo + link BGG');
chk(/ibgg_viaUserHelp/.test(brand)&&/ibgg_attrib/.test(brand),'testi configurabili nuovi');
chk(/invoke\('bgg-meta'/.test(des),'desideri resta su bgg-meta');
chk(/DS\.bgg/.test(giochi),'giochi usa DS.bgg → bgg-meta');
chk(/invoke\('bgg-meta'/.test(cons),'consigliere resta su bgg-meta');
chk(fs.existsSync(path.join(root,'img/powered-by-bgg.png')),'asset logo presente');
chk(fs.existsSync(path.join(root,'supabase/migrate-v41.10.sql')),'migrazione locale pronta');
chk(/APP_VERSION='41\.10'/.test(brand),'APP_VERSION 41.10');
function parseSearch(xml){const out=[];for(const m of xml.matchAll(/<item\b([^>]*)>([\s\S]*?)<\/item>/g)){const id=+(m[1].match(/\bid="(\d+)"/)||[])[1];const nm=(m[2].match(/<name[^>]*value="([^"]*)"/)||[])[1];if(id&&nm)out.push({bgg_id:id,nome:nm})}return out}
chk(parseSearch('<items><item id="13" type="boardgame"><name type="primary" value="Catan"/><yearpublished value="1995"/></item></items>')[0]?.bgg_id===13,'parser search Catan');
console.log(`\n${ok}/${n} controlli`);
if(ok!==n)process.exit(1);
